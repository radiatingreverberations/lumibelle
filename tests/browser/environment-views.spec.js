async function choose(page, setModel = true, valid = true) {
  await page.getByRole('button', { name: 'Choose environment views', exact: true }).click();
  const review = page.getByRole('dialog', { name: 'Choose environment views', exact: true });
  if (setModel) {
    await review.locator('.model-chip').click();
    await page.getByRole('combobox', { name: 'Text model', exact: true }).selectOption({ label: 'OpenRouter · Alternate mock model' });
    await page.getByRole('button', { name: 'Set as project default', exact: true }).click();
  }
  await review.getByRole('button', { name: 'Choose views with AI', exact: true }).click();
  if (valid) {
    await expect(review.getByText('Review the proposed views before applying them.', { exact: true })).toBeVisible({ timeout: 45000 });
    await expect(review.getByRole('button', { name: 'Apply views', exact: true })).toBeEnabled();
  } else await expect(review.getByRole('alert')).toContainText('not a complete environment selection');
  return review;
}
