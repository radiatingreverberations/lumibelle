import { test, expect } from './fixtures.js';

for (const width of [1280, 390]) test(`project style, asset inheritance and batch overrides stay captured at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width, height: 1000 });
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/bulk-reels`);
  await request.post('/fixtures/bulk-assets/vision');
  await page.goto(`/projects/${id}/settings`);
  const project = page.locator('.project-visual-style');
  await project.getByRole('combobox', { name: 'Project visual style', exact: true }).selectOption('Anime');
  await project.getByLabel('Project visual style direction', { exact: true }).fill('Muted greens and crisp linework.');
  await project.getByRole('button', { name: 'Save visual style', exact: true }).click();
  await expect(project).toContainText('Visual style saved.');
  await project.screenshot({ path: testInfo.outputPath(`project-style-${width}.png`) });
  await page.reload();
  await expect(project.getByRole('combobox', { name: 'Project visual style', exact: true })).toHaveValue('Anime');
  await expect(project.getByLabel('Project visual style direction', { exact: true })).toHaveValue('Muted greens and crisp linework.');
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  await page.getByRole('button', { name: 'Edit asset details', exact: true }).click();
  const details = page.locator('.asset-details-dialog');
  await details.getByRole('combobox', { name: 'Asset visual style', exact: true }).selectOption('Illustration');
  await details.getByLabel('Asset visual style direction', { exact: true }).fill('Ink wash on textured paper.');
  await details.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(details).not.toBeVisible();
  const toggle = page.locator('[data-toggle-pane=left]');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await page.locator('.bulk-assets-launch').click();
  const batch = page.locator('.asset-batch-dialog');
  await expect(batch.getByRole('combobox', { name: 'Batch visual style', exact: true })).toHaveValue('inherit');
  await batch.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(batch.locator('.bulk-select-actions')).toContainText('0 items');
  await batch.locator('.bulk-plan-card').first().getByRole('checkbox').first().check();
  await expect(batch.locator('.bulk-select-actions')).toContainText('1 items');
  await batch.getByRole('button', { name: 'Review generation plan', exact: true }).click();
  await expect(batch.locator('.bulk-style-direction')).toContainText('Illustration');
  await expect(batch.locator('.bulk-style-direction p')).toContainText('Ink wash');
  await batch.getByRole('button', { name: 'Back to selection', exact: true }).click();
  await batch.getByRole('combobox', { name: 'Batch visual style', exact: true }).selectOption('Photographic');
  await batch.getByLabel('Batch visual style direction', { exact: true }).fill('Soft daylight and muted colours.');
  await batch.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(batch.locator('.bulk-select-actions')).toContainText('0 items');
  await batch.locator('.bulk-plan-card').first().getByRole('checkbox').first().check();
  await expect(batch.locator('.bulk-select-actions')).toContainText('1 items');
  await batch.getByRole('checkbox', { name: 'Evaluate candidates with a vision model' }).check();
  await batch.getByRole('button', { name: 'Review generation plan', exact: true }).click();
  await expect(batch.locator('.bulk-style-direction')).toContainText('Photographic');
  await batch.getByRole('button', { name: 'Start batch', exact: true }).click();
  await expect(batch.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 45000 });
  await expect(batch).toContainText('Captured visual style · Photographic');
  const captures = await (await request.get(`/fixtures/${id}/visual-style`)).json();
  expect(captures.project.preset).toBe('Anime');
  expect(captures.generation).toHaveLength(1);
  expect(captures.generation[0].preset).toBe('Photographic');
  expect(captures.generation[0].prompt).toContain('Soft daylight and muted colours.');
  expect(captures.generation[0].originalPrompt).not.toContain('Visual style direction:');
  expect(captures.reviews).toHaveLength(1);
  expect(captures.reviews[0].prompt).toContain('Soft daylight and muted colours.');
  expect(await batch.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
});
