import { test, expect } from './fixtures.js';
import { scriptAssist, modelOptions } from './text-assistance-tools.js';

test('selected shot and asset details inform a reviewed script proposal without changing the script on submission', async ({ page, request }) => {
  const { id } = await (await request.get('/fixtures/new')).json();
  const library = await (await request.post(`/fixtures/${id}/images`)).json();
  await request.post(`/fixtures/${id}/approved`);
  await request.post(`/fixtures/${id}/production-shot`);
  const before = (await (await request.get(`/fixtures/${id}`)).json()).script;
  const shot = (await (await request.get(`/fixtures/${id}/shots`)).json()).shots[0];
  await page.goto(`/projects/${id}/script`);
  await scriptAssist(page);
  await page.locator('#script-scope').selectOption('Document');
  await page.getByLabel('Instructions', { exact: true }).fill('Reflect the attached shot action and asset descriptions in this script.');
  await page.getByRole('button', { name: 'Manage references', exact: true }).click();
  const context = page.locator('.writing-reference-dialog');
  await context.getByRole('button', { name: 'Shots', exact: true }).click();
  await context.getByRole('checkbox', { name: `Select shot 1: ${shot.title}`, exact: true }).check();
  await context.getByRole('button', { name: 'Asset details', exact: true }).click();
  await context.locator('.context-asset').filter({ hasText: library.assets[0].name }).click();
  await context.locator('.context-preview').first().locator('summary').click();
  await expect(context.locator('pre').first()).toContainText(shot.description);
  await context.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.locator('.context-summary li')).toHaveCount(2);
  await page.getByRole('button', { name: 'Revise', exact: true }).click();
  const review = page.locator('.script-review-dialog');
  await expect(review).toBeVisible();
  await review.getByText('Request details', { exact: true }).click();
  await expect(review.locator('.submitted-input')).toContainText('SELECTED SHOTS AND ASSETS');
  await expect(review.locator('.submitted-input')).toContainText(shot.description);
  const proposed = (await (await request.get(`/fixtures/${id}`)).json()).script;
  expect(proposed.blocks).toEqual(before.blocks);
  await review.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(review).toBeHidden();
  await expect.poll(async () => (await (await request.get(`/fixtures/${id}`)).json()).script.blocks).not.toEqual(before.blocks);
  expect((await (await request.get(`/fixtures/${id}/shots`)).json()).shots[0]).toEqual(shot);
});

for (const width of [1440, 390]) test(`writing reference images use the shared picker, cancel safely and require a vision model (${width})`, async ({ page, request }) => {
  await page.setViewportSize({ width, height: 900 });
  const { id } = await (await request.get('/fixtures/new')).json();
  const library = await (await request.post(`/fixtures/${id}/images?patterned=true`)).json();
  await request.post(`/fixtures/${id}/approved`);
  const before = (await (await request.get(`/fixtures/${id}`)).json()).script;
  await page.goto(`/projects/${id}/script`);
  await scriptAssist(page);
  await page.locator('#script-scope').selectOption('Document');
  await page.getByLabel('Instructions', { exact: true }).fill('Revise the scene using image 1.');
  const open = page.getByRole('button', { name: 'Manage references', exact: true });
  const dialog = page.locator('.writing-reference-dialog');
  await open.click();
  const images = dialog.locator('.picker-image');
  await expect(images).toHaveCount(2);
  await expect.poll(() => images.first().locator('img').evaluate(i => i.complete && i.naturalWidth > 0)).toBe(true);
  await images.first().click();
  await images.last().click();
  if (width < 650) await dialog.getByRole('tab', { name: 'Selected references (2)', exact: true }).click();
  const rows = dialog.locator('.reference-selection-row');
  await expect(rows).toHaveCount(2);
  const lastTitle = await rows.last().locator('strong').innerText();
  await rows.last().getByRole('button', { name: /^Move .* up$/ }).click();
  await expect(rows.first().locator('strong')).toHaveText(lastTitle.replace('Image 2', 'Image 1'));
  await rows.last().getByRole('button', { name: /^Remove / }).click();
  await expect(rows).toHaveCount(1);
  await page.screenshot({ path: `artifacts/writing-references-${width}.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await dialog.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(page.locator('.context-summary li')).toHaveCount(1);
  const applied = await page.locator('.context-summary strong').allTextContents();
  await expect(page.locator('.script-project-context')).toContainText('The selected model cannot read images');
  await expect(page.getByRole('button', { name: 'Revise', exact: true })).toBeDisabled();
  await open.click();
  await dialog.getByRole('button', { name: 'Clear', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.locator('.context-summary strong')).toHaveText(applied);

  const options = await modelOptions(page, page.locator('.script-assistant'));
  await options.getByRole('combobox', { name: 'Text model', exact: true }).selectOption({ label: 'OpenRouter · Alternate mock model' });
  await options.getByRole('button', { name: 'Done', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Revise', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Revise', exact: true }).click();
  const review = page.locator('.script-review-dialog');
  await expect(review).toBeVisible();
  await review.getByText('Request details', { exact: true }).click();
  await expect(review.locator('.submitted-input')).toContainText('SELECTED REFERENCE IMAGES');
  await expect(review.locator('.submitted-input')).toContainText('Image 1');
  const job = (await (await request.get('/fixtures/ai-jobs')).json()).find(j => j.target.projectId === id && j.kind === 'ScriptAssistant');
  const captured = await (await request.get(`/fixtures/ai-jobs/${job.id}/text-selection`)).json();
  expect(captured.imageCount).toBe(1);
  expect((await (await request.get(`/fixtures/${id}`)).json()).script.blocks).toEqual(before.blocks);
});
