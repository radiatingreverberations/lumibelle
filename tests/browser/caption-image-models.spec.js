import { test, expect } from './fixtures.js';
import { toolsTab } from './workspace-tools.js';

for (const width of [1280, 390]) {
  test(`Fibo, Z-Image and Qwen Turbo settings persist independently at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 960 });
    await page.goto('/settings/ai?tab=images');
    await expect(page.locator('h1')).toBeFocused();
    await page.locator('#ai-image-Fibo2').click();
    await expect(page.locator('#caption-image-steps')).toHaveValue('50');
    await expect(page.locator('#comfy-image-edit-lora')).toHaveCount(0);
    await page.getByRole('button', { name: 'Refresh image models', exact: true }).click();
    await page.locator('#comfy-image-model').selectOption('fibo2_edit_turbo_int8_convrot.safetensors');
    await page.locator('#caption-image-variant').selectOption('Turbo');
    await expect(page.locator('#caption-image-steps')).toHaveValue('4');
    await expect(page.locator('#caption-image-guidance')).toHaveCount(0);
    await page.getByRole('button', { name: 'Save Fibo 2.0', exact: true }).click();
    await expect(page.getByText('Fibo 2.0 saved.', { exact: true })).toBeVisible();
    await page.locator('#ai-image-ZImage').click();
    await expect(page.locator('#caption-image-steps')).toHaveValue('8');
    await page.getByRole('button', { name: 'Refresh image models', exact: true }).click();
    await page.locator('#comfy-image-model').selectOption('z_image_bf16.safetensors');
    await page.locator('#caption-image-variant').selectOption('Base');
    await expect(page.locator('#caption-image-steps')).toHaveValue('25');
    await expect(page.locator('#caption-image-guidance')).toHaveValue('4');
    await page.locator('#caption-image-shift').fill('4');
    await page.getByRole('button', { name: 'Save Z-Image', exact: true }).click();
    await expect(page.getByText('Z-Image saved.', { exact: true })).toBeVisible();
    await page.locator('#ai-image-QwenImage21').click();
    await page.getByRole('button', { name: 'Refresh image models', exact: true }).click();
    await page.locator('#comfy-image-model').selectOption('qwen_image_2.1_turbo_int8_convrot.safetensors');
    await page.locator('#qwen-image-variant').selectOption('Turbo');
    await page.getByRole('button', { name: 'Save Qwen Image 2.1', exact: true }).click();
    await expect(page.getByText('Qwen Image 2.1 saved.', { exact: true })).toBeVisible();
    await page.reload(); await expect(page.locator('h1')).toBeFocused();
    await page.locator('#ai-image-Fibo2').click();
    await expect(page.locator('#caption-image-variant')).toHaveValue('Turbo');
    await expect(page.locator('#comfy-image-model')).toHaveValue('fibo2_edit_turbo_int8_convrot.safetensors');
    await page.locator('#ai-image-ZImage').click();
    await expect(page.locator('#caption-image-variant')).toHaveValue('Base');
    await expect(page.locator('#caption-image-shift')).toHaveValue('4');
    await page.locator('#ai-image-QwenImage21').click();
    await expect(page.locator('#qwen-image-variant')).toHaveValue('Turbo');
    await page.locator('#ai-image-Krea2').click();
    await expect(page.locator('#comfy-image-edit-lora')).toHaveValue('krea2_identity_edit_v1_2.safetensors');
    await page.locator('#ai-image-Fibo2').click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
    await page.screenshot({ path: `test-results/caption-model-settings-${width}.png`, fullPage: true });
  });
}

test('Qwen Turbo uses eight steps in Assets and Z-Image explains its editing limitation', async ({ page, request }) => {
  await page.goto('/settings/ai?tab=images'); await expect(page.locator('h1')).toBeFocused();
  await page.locator('#ai-image-QwenImage21').click();
  await page.getByRole('button', { name: 'Refresh image models', exact: true }).click();
  await page.locator('#comfy-image-model').selectOption('qwen_image_2.1_turbo_int8_convrot.safetensors');
  await page.locator('#qwen-image-variant').selectOption('Turbo');
  await page.getByRole('button', { name: 'Save Qwen Image 2.1', exact: true }).click();
  await expect(page.getByText('Qwen Image 2.1 saved.', { exact: true })).toBeVisible();
  await page.locator('#ai-image-Fibo2').click();
  await page.getByRole('button', { name: 'Refresh image models', exact: true }).click();
  await page.locator('#comfy-image-model').selectOption('fibo2_edit_turbo_int8_convrot.safetensors');
  await page.locator('#caption-image-variant').selectOption('Turbo');
  await page.getByRole('button', { name: 'Save Fibo 2.0', exact: true }).click();
  await expect(page.getByText('Fibo 2.0 saved.', { exact: true })).toBeVisible();
  const project = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${project.id}/images`);
  await page.goto(`/projects/${project.id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  await toolsTab(page, 'Prompt');
  const workflow = page.getByLabel('Image workflow', { exact: true });
  await workflow.selectOption('QwenImage21');
  await page.locator('.image-generation-settings summary').click();
  await expect(page.locator('#qwen-image-steps')).toHaveValue('8');
  await expect(page.locator('#qwen-image-steps')).toBeDisabled();
  await page.locator('.asset-media-card[data-media-kind=Image] .media-select').click();
  await toolsTab(page, 'Prompt');
  await workflow.selectOption('Fibo2');
  await page.getByLabel('Edit instruction', { exact: true }).fill('Make the coat blue while preserving the framing.');
  await expect(page.getByRole('button', { name: 'Generate edited images', exact: true })).toBeEnabled();
  await workflow.selectOption('ZImage');
  await expect(page.locator('.image-workflow-issue')).toContainText('support creation');
  await expect(page.getByRole('button', { name: 'Generate edited images', exact: true })).toBeDisabled();
});
