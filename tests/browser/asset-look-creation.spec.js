import { test, expect } from './fixtures.js';

for (const narrow of [false, true]) test(`look descriptions and identity-backed creation (${narrow ? 'narrow' : 'desktop'})`, async ({ page, request }) => {
  const { id } = await (await request.get('/fixtures/new')).json();
  expect((await request.post(`/fixtures/${id}/images?patterned=true`)).ok()).toBeTruthy();
  expect((await request.post(`/fixtures/${id}/look-creation`)).ok()).toBeTruthy();
  const library = (await (await request.get(`/fixtures/${id}`)).json()).assets;
  const owner = library.assets[0], look = owner.looks[0];
  await page.setViewportSize({ width: narrow ? 390 : 1500, height: narrow ? 844 : 1050 });
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const overview = page.locator('.asset-gallery-groups');
  await expect(page.locator('.character-look-overview')).toHaveCount(0);
  await expect(overview.locator('.look-card')).toHaveCount(2);
  await expect(overview).toContainText(look.description);
  await expect(overview.locator('.look-card').first()).toContainText('0 images');
  await expect(overview.locator('.asset-gallery-group').first()).toContainText('General');
  await expect(overview.getByRole('button', { name: `Create images for ${look.name}`, exact: true })).toHaveCount(1);
  await page.screenshot({ path: `test-results/asset-look-overview-${narrow ? 'narrow' : 'desktop'}.png`, fullPage: true });
  await overview.getByRole('button', { name: `Create images for ${look.name}`, exact: true }).click();
  const notes = page.getByRole('region', { name: 'Selected look notes', exact: true });
  await expect(notes).toContainText(look.description);
  expect(await page.locator('#image-prompt').inputValue()).toContain(look.description);
  await expect(page.locator('.compact-image-input img')).toHaveAttribute('src', new RegExp(owner.images[0].id));
  await expect(page.locator('#assets-tool-heading')).toHaveText('Create image');
  await page.locator('#image-prompt').fill('My authored raincoat direction.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  await page.screenshot({ path: `test-results/asset-look-composer-${narrow ? 'narrow' : 'desktop'}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Generate images', exact: true }).click();
  await expect.poll(async () => {
    const current = (await (await request.get(`/fixtures/${id}`)).json()).assets;
    return current.assets.find(asset => asset.id === owner.id).images.some(image => image.lookId === look.id);
  }).toBeTruthy();
  const current = (await (await request.get(`/fixtures/${id}`)).json()).assets;
  const source = current.assets.find(asset => asset.id === owner.id).images.find(image => image.id === owner.images[0].id);
  expect(source.lookId).toBeNull();
  expect(source.isReference).toBeTruthy();
  const review = page.locator('.image-review-dialog');
  await expect(review).toBeVisible();
  await review.getByRole('button', { name: 'Close', exact: true }).last().click();
  await expect(review).toBeHidden();
  const lookGroup = overview.locator(`.asset-gallery-group[data-look-id="${look.id}"]`);
  await expect(lookGroup.locator('.asset-media-card')).toHaveCount(1);
  await expect(lookGroup).toContainText(look.description);
  await expect(lookGroup.getByRole('button', { name: `Create images for ${look.name}`, exact: true })).toHaveCount(1);
  if (narrow) await page.locator('.workspace-right .workspace-drawer-heading [data-close-pane]').click();
  await lookGroup.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy();
  await page.screenshot({ path: `test-results/asset-look-unified-${narrow ? 'narrow' : 'desktop'}.png`, fullPage: true });
});
