import { test, expect } from './fixtures.js';

for (const width of [1280, 390]) test(`candidate review keeps, discards and undoes only undecided images at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width, height: 1000 });
  const { id } = await (await request.get('/fixtures/new')).json();
  expect((await request.post(`/fixtures/${id}/review-assets`)).ok()).toBeTruthy();
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const toggle = page.locator('[data-toggle-pane=left]');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  const launch = page.locator('.bulk-assets-launch');
  await launch.click();
  const dialog = page.locator('.asset-batch-dialog');
  await dialog.getByLabel('Candidates per item').selectOption('4');
  await dialog.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('0 items');
  await dialog.locator('.bulk-plan-card').first().getByRole('checkbox').first().check();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('1 items');
  await dialog.getByRole('button', { name: 'Review generation plan', exact: true }).click();
  await dialog.getByRole('button', { name: 'Start batch', exact: true }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 45000 });
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(4);
  await expect(dialog.getByRole('button', { name: 'Discard all remaining candidates (4)', exact: true })).toBeEnabled();
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.locator('.asset-media-gallery .asset-media-card')).toHaveCount(0);
  await expect(page.locator('.asset-pending-review')).toContainText('4 candidates');
  await launch.click();
  await dialog.getByRole('button', { name: 'Keep as take', exact: true }).first().click();
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(3);
  await dialog.getByRole('button', { name: 'Use as reference', exact: true }).first().click();
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(2);
  await expect(launch).toContainText('Review bulk assets · 1');
  await page.reload();
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await expect(page.locator('.asset-media-gallery .asset-media-card')).toHaveCount(2);
  await launch.click();
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(2);
  await dialog.getByRole('button', { name: 'Discard all remaining candidates (2)', exact: true }).click();
  await expect(dialog.locator('.bulk-review-complete')).toBeVisible();
  await expect(launch).toHaveText('Bulk assets');
  let library = (await (await request.get(`/fixtures/${id}`)).json()).assets;
  expect(library.assets[0].images).toHaveLength(2);
  expect(library.assets[0].images.filter(i => i.isReference)).toHaveLength(1);
  expect(library.trash).toHaveLength(2);
  await dialog.getByRole('combobox', { name: 'Candidate review filter', exact: true }).selectOption('all');
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(4);
  await expect(dialog.locator('.bulk-candidate-decision').filter({ hasText: 'Discarded' })).toHaveCount(2);
  await expect(dialog.locator('.bulk-candidate-decision').filter({ hasText: 'Kept as take' })).toHaveCount(1);
  await expect(dialog.locator('.bulk-candidate-decision').filter({ hasText: 'Reference approved' })).toHaveCount(1);
  await dialog.getByRole('button', { name: 'Undo discard', exact: true }).click();
  await expect(dialog.locator('.bulk-review-toolbar')).toContainText('2 candidates awaiting');
  await expect(dialog.locator('.bulk-discard-undo')).toHaveCount(0);
  library = (await (await request.get(`/fixtures/${id}`)).json()).assets;
  expect(library.trash).toHaveLength(0);
  expect(library.assets[0].images.filter(i => i.pendingReview)).toHaveLength(2);
  await dialog.getByRole('combobox', { name: 'Candidate review filter', exact: true }).selectOption('pending');
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(2);
  await dialog.getByRole('button', { name: 'Discard', exact: true }).first().click();
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(1);
  await expect(dialog.locator('.bulk-review-toolbar')).toContainText('1 candidate awaiting');
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.screenshot({ path: testInfo.outputPath(`candidate-review-${width}.png`) });
});
