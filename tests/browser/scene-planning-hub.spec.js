for (const width of [1440, 430]) test(`Scenes lists empty scenes and restores the remembered selection at ${width}px`, async ({ page, request }) => {
  const { id } = await (await request.get('/fixtures/new')).json();
  const scenes = await (await request.post(`/fixtures/${id}/long-scene-list`)).json();
  const sceneId = scenes[55].id;
  await page.setViewportSize({ width, height: 950 });
  await page.goto(`/projects/${id}/scenes?sceneId=${sceneId}`);
  await expect(page.locator('.shots-heading')).toHaveAttribute('data-interactive', 'true');
  await expect(page.locator('.scene-outline-item')).toHaveCount(60);
  const selected = page.locator(`.scene-outline-item[data-scene-id='${sceneId}']`);
  await expect(selected).toHaveClass(/selected/);
  await expect.poll(() => page.evaluate(id => JSON.parse(localStorage.getItem(`lumibelle.position.${id}.scenes.v1.data`))?.scene, id)).toBe(sceneId);
  await page.evaluate(() => history.replaceState(null, '', location.pathname));
  await page.reload();
  await expect(page.locator('.shots-heading')).toHaveAttribute('data-interactive', 'true');
  if (width === 430) await page.locator('[data-toggle-pane=left]').click();
  await expect(selected).toBeInViewport();
  await selected.click();
  await expect(page.locator('.scene-hub-section').last()).toContainText('No shots yet');
  await page.getByRole('link', { name: 'Edit in Script', exact: true }).click();
  await expect(page).toHaveURL(/\/script$/);
  await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Scenes', exact: true }).click();
  await expect(selected).toHaveClass(/selected/);
});
