async function showEnvironment(page) {
  const root = page.locator('.studio-workspace[data-studio="Scenes"]');
  await expect(root).toHaveAttribute('data-ready', 'true');
  await expect(root).not.toHaveAttribute('data-suspended', 'true');
  const toggle = page.getByRole('button', { name: 'Show Scene environment', exact: true });
  if (!await root.locator('.workspace-right').isVisible()) await toggle.click();
  await expect(root.locator('.workspace-right')).toBeVisible();
}

async function closeEnvironmentDrawer(page) {
  const close = page.getByRole('button', { name: 'Close Scene environment', exact: true });
  if (await close.isVisible()) await close.click();
}

