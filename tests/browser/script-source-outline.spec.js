import { test, expect } from './fixtures.js';

test('an accepted source outline drafts reviewed additions and remembers sequence progress', async ({ page, request }) => {
  test.setTimeout(120000);
  const { id } = await (await request.get('/fixtures/new')).json();
  await page.goto(`/projects/${id}/source`);
  await page.getByLabel('Source title', { exact: true }).fill('The river key');
  await page.getByLabel('Original text', { exact: true }).fill('Chapter 1\nEira inherits a brass key and follows the river.\n\nChapter 2\nThe key opens a gate onto a sheltered garden.');
  await page.getByRole('button', { name: 'Analyze source', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Accept outline', exact: true })).toBeEnabled({ timeout: 60000 });
  await page.getByRole('button', { name: 'Accept outline', exact: true }).click();
  await page.getByRole('navigation', { name: 'Project navigation' }).getByRole('link', { name: 'Script', exact: true }).click();
  const progress = page.locator('.script-source-progress');
  await expect(progress).toContainText('0 of 2 sequences added');
  await expect(page.getByLabel('Sequence to draft', { exact: true })).toHaveValue('0:0');
  await page.getByLabel('Use accepted outline', { exact: true }).uncheck();
  await page.getByLabel('Use accepted outline', { exact: true }).check();
  await expect(page.getByLabel('Action', { exact: true })).toHaveValue('outline-scene');
  await expect(page.getByLabel('Work on', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Draft sequence', exact: true }).click();
  const review = page.getByRole('dialog').filter({ hasText: 'Review script proposal' });
  await expect(review.getByRole('button', { name: 'Apply changes', exact: true })).toBeEnabled({ timeout: 30000 });
  await expect(review).toContainText('Draft sequence 1.1');
  expect((await (await request.get(`/fixtures/${id}`)).json()).script.sourceSceneLinks).toEqual([]);
  await review.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(progress).toContainText('1 of 2 sequences added');
  const first = (await (await request.get(`/fixtures/${id}`)).json()).script;
  await page.reload();
  await expect(progress).toContainText('1 of 2 sequences added');
  await expect(page.getByLabel('Sequence to draft', { exact: true })).toHaveValue('1:0');
  await page.getByLabel('Act', { exact: true }).selectOption('0');
  await expect(page.getByRole('button', { name: 'Draft sequence', exact: true })).toBeDisabled();
  await page.getByLabel('Act', { exact: true }).selectOption('1');
  await page.getByRole('button', { name: 'Draft sequence', exact: true }).click();
  await expect(review.getByRole('button', { name: 'Apply changes', exact: true })).toBeEnabled({ timeout: 30000 });
  await review.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(progress).toContainText('2 of 2 sequences added');
  const second = (await (await request.get(`/fixtures/${id}`)).json()).script;
  expect(second.blocks.slice(0, first.blocks.length)).toEqual(first.blocks);
  expect(second.sourceSceneLinks).toHaveLength(2);
  await page.screenshot({ path: 'artifacts/script-source-outline.png', fullPage: true });
});
