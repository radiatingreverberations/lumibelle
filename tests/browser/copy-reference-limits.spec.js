import { test, expect } from './fixtures.js';
import { toolsTab } from './workspace-tools.js';

for (const narrow of [false, true]) test(`Repair copied reference budgets in the shared editor (${narrow ? 'narrow' : 'desktop'})`, async ({ page, request }) => {
  test.setTimeout(120000);
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/images`);
  await request.post(`/fixtures/${id}/approved`);
  await request.post(`/fixtures/${id}/production-shot`);
  const take = await (await request.post(`/fixtures/${id}/reference-video-take`)).json();
  await request.post(`/fixtures/${id}/reference-reels?takeId=${take.id}`);
  await request.post(`/fixtures/${id}/production-shot`);
  const fixture = await request.post(`/fixtures/${id}/copy-reference-limits`);
  expect(fixture.ok(), await fixture.text()).toBe(true);
  const { names } = await fixture.json();
  const saved = async () => (await (await request.get(`/fixtures/${id}/production`)).json());
  const before = await saved();
  await page.setViewportSize({ width: 1152, height: 1000 });
  await page.goto(`/projects/${id}/shots`);
  await toolsTab(page, 'References');
  const target = page.locator('[data-shot-id]').nth(1);
  await target.click();
  // The click returns before Blazor finishes switching shots. Wait for the target
  // render so Copy cannot arrive against the previous shot during that transition.
  await expect(target).toHaveAttribute('aria-pressed', 'true');
  if (narrow) await page.setViewportSize({ width: 390, height: 844 });
  await toolsTab(page, 'References');
  const copying = page.getByRole('dialog', { name: 'Copy references from shot', exact: true });
  const editor = page.getByRole('dialog', { name: 'Manage references', exact: true });
  const open = async () => {
    await page.getByRole('button', { name: 'Copy from shot…', exact: true }).click();
    await expect(copying).toContainText('this shot has 13');
    await copying.getByRole('button', { name: 'Copy and edit references', exact: true }).click();
    await expect(copying).toBeHidden();
    await expect(editor).toBeVisible();
    await expect(page.getByRole('dialog')).toHaveCount(1);
    await expect(editor.getByRole('button', { name: 'Apply changes', exact: true })).toBeDisabled();
  };
  await open();
  await editor.getByRole('button', { name: 'Remove Picture 9', exact: true }).click();
  await expect(editor).toContainText('16 s');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(editor).toBeHidden();
  expect(await saved()).toEqual(before);
  await open();
  await editor.getByRole('button', { name: 'Remove Picture 9', exact: true }).click();
  for (const name of names) await editor.getByRole('spinbutton', { name: `Audio duration for ${name}`, exact: true }).fill('7');
  await editor.getByRole('spinbutton', { name: `Audio duration for ${names[1]}`, exact: true }).press('Tab');
  await expect(editor.getByRole('button', { name: 'Apply changes', exact: true })).toBeEnabled();
  expect(await editor.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: `artifacts/copy-reference-repair-${narrow ? 'narrow' : 'desktop'}.png` });
  await editor.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(editor).toBeHidden();
  await expect.poll(async () => (await saved()).shotContent[1].images.length).toBe(8);
  const after = await saved();
  expect(after.shotContent[1].voices.map(v => v.duration)).toEqual([7, 7]);
  expect(after.shotContent[1].videos).toHaveLength(2);
  expect(after.shotContent[0]).toEqual(before.shotContent[0]);
  if (narrow) await page.getByRole('button', { name: 'Close Shot tools', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await saved()).shotContent[1]).toEqual(before.shotContent[1]);
});
