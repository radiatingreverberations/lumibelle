import { test, expect } from './fixtures.js';

for (const [width, kind] of [[1280, 'CharacterReels'], [390, 'EnvironmentReels']]) test(`bulk ${kind} captures recipes and saves keyframes only after approval at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(120000);
  await page.setViewportSize({ width, height: 960 });
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/bulk-reels`); await request.post('/fixtures/bulk-assets/vision');
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const toggle = page.locator('[data-toggle-pane=left]');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await page.locator('.bulk-assets-launch').click();
  const dialog = page.locator('.asset-batch-dialog');
  await dialog.getByRole('combobox', { name: 'Output type', exact: true }).selectOption(kind);
  await expect(dialog.locator('.bulk-plan-card')).toHaveCount(kind === 'CharacterReels' ? 2 : 1);
  await dialog.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('0 items');
  await dialog.locator('.bulk-plan-card').first().getByRole('checkbox').first().check();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('1 items');
  await dialog.getByRole('checkbox', { name: 'Evaluate candidates with a vision model' }).check();
  await dialog.getByRole('button', { name: 'Review generation plan' }).click();
  await expect(dialog.getByLabel('Generation prompt')).not.toBeEmpty();
  await expect(dialog.getByRole('button', { name: 'Start batch', exact: true })).toBeEnabled();
  await dialog.locator('.bulk-steps').scrollIntoViewIfNeeded();
  await expect(dialog.locator('.bulk-steps .active')).toBeVisible();
  await dialog.screenshot({ path: testInfo.outputPath('reel-plan.png') });
  await dialog.getByRole('button', { name: 'Start batch', exact: true }).click();
  await dialog.getByRole('button', { name: 'Pause after current request' }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch paused');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload(); await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await page.locator('.bulk-assets-launch').click();
  await dialog.getByRole('button', { name: 'Resume batch' }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 60000 });
  await expect(dialog.locator('.bulk-reel-candidate')).toHaveCount(1);
  await expect(dialog.locator('.bulk-reel-candidate')).toContainText('sampled views');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(page.locator('.bulk-assets-launch')).toContainText('Review bulk assets · 1');
  await expect(page.locator('.asset-library-bulk .request-ready .ai-assist-icon')).toBeVisible();
  await page.locator('.bulk-assets-launch').click();
  const state = async () => (await (await request.get(`/fixtures/${id}`)).json()).assets;
  expect((await state()).reels[0].keyframes).toBeFalsy();
  await expect(dialog.getByRole('button', { name: 'Save selected keyframes' })).toBeEnabled();
  await dialog.getByRole('button', { name: 'Save selected keyframes' }).click();
  await expect(dialog.locator('.bulk-reel-candidate')).toContainText('Keyframes reviewed and saved');
  await expect(page.locator('.bulk-assets-launch')).toHaveText('Bulk assets');
  expect((await state()).reels[0].keyframes.frames.length).toBeGreaterThan(0);
  await dialog.getByRole('button', { name: 'Review video & keyframes', exact: true }).click();
  const keyframes = page.locator('.bulk-reel-keyframe-dialog');
  await expect(keyframes).toBeVisible();
  await keyframes.getByLabel('Frame notes (optional)').first().fill('Use this held view for appearance only.');
  await keyframes.getByRole('button', { name: 'Save keyframes', exact: true }).click();
  await expect(keyframes).not.toBeVisible();
  await expect(dialog).toBeVisible();
  expect((await state()).reels[0].keyframes.frames[0].notes).toBe('Use this held view for appearance only.');
  await dialog.getByRole('button', { name: 'Review video & keyframes', exact: true }).click();
  await expect(keyframes).toBeVisible();
  await keyframes.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(keyframes).not.toBeVisible();
  await expect(dialog).toBeVisible();
  const batches = await (await request.get(`/fixtures/${id}/asset-batches`)).json();
  expect(batches[0].items[0].generationJobs).toHaveLength(1);
  expect(batches[0].items[0].reviewedReels).toHaveLength(1);
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.screenshot({ path: testInfo.outputPath('reel-results.png') });
  await dialog.getByRole('button', { name: 'New batch', exact: true }).click();
  await dialog.getByRole('combobox', { name: 'Output type', exact: true }).selectOption(kind);
  await expect(dialog.locator('.bulk-plan-card').first()).toContainText('Has saved coverage');
});
