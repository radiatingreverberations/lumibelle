test('untested OpenRouter stars offer a keyboard accessible warning, test shortcut and explicit override', async ({ page, request }) => {
  const before = await snapshot(request);
  await page.goto('/settings/ai?tab=text&provider=openrouter');
  await expect(page.locator('h1')).toBeFocused();
  await page.getByLabel('Search text models', { exact: true }).fill('Catalog model 29');
  const row = page.locator('.text-model-row');
  const star = row.getByRole('button', { name: 'Star Catalog model 29', exact: true });
  const warning = row.getByRole('region', { name: 'Test before starring', exact: true });
  const dialog = page.getByRole('dialog', { name: 'Model details & test', exact: true });
  await expect(row).toHaveCount(1);
  await expect(row).toContainText('Not tested');
  const jobsBefore = (await (await request.get('/fixtures/ai-jobs')).json()).length;
  await star.focus(); await page.keyboard.press('Enter');
  await expect(warning.getByRole('alert')).toContainText('Catalog discovery does not test generation');
  expect((await snapshot(request)).starredTextModels).toEqual(before.starredTextModels);
  await warning.getByRole('button', { name: 'Cancel', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(warning).toHaveCount(0);
  await star.click();
  await page.setViewportSize({ width: 1173, height: 1272 });
  await page.screenshot({ path: 'artifacts/openrouter-star-warning-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(warning.getByRole('button', { name: 'Test model', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await warning.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/openrouter-star-warning-mobile.png' });
  await warning.getByRole('button', { name: 'Star anyway', exact: true }).click();
  await expect(row.getByRole('button', { name: 'Unstar Catalog model 29', exact: true })).toBeVisible();
  expect((await (await request.get('/fixtures/ai-jobs')).json()).length).toBe(jobsBefore);
  await row.getByRole('button', { name: 'Unstar Catalog model 29', exact: true }).click();
  await expect(star).toBeVisible(); await star.click();
  await warning.getByRole('button', { name: 'Test model', exact: true }).click();
  await expect(dialog).toBeVisible();
  expect((await (await request.get('/fixtures/ai-jobs')).json()).length).toBe(jobsBefore);
  await dialog.getByRole('button', { name: 'Run benchmark · 2,048 total tokens', exact: true }).click();
  await expect(dialog).toContainText('Test result saved.');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(row).toContainText('Benchmark completed');
  await star.click();
  await expect(row.getByRole('button', { name: 'Unstar Catalog model 29', exact: true })).toBeVisible();
  await expect(warning).toHaveCount(0);
  await page.reload();
  await expect(page.locator('h1')).toBeFocused();
  await page.getByLabel('Search text models', { exact: true }).fill('Catalog model 29');
  await expect(row).toHaveCount(1);
  await expect(row).toContainText('Benchmark completed');
  await row.getByRole('button', { name: 'Unstar Catalog model 29', exact: true }).click();
  await expect(star).toBeVisible();
  const after = await snapshot(request);
  expect(after.starredTextModels).toEqual(before.starredTextModels);
  expect(after.defaultBackend).toBe(before.defaultBackend); expect(after.openRouterModel).toBe(before.openRouterModel);
});

test('ComfyUI generation defaults retain drafts and save independently of shared timeouts', async ({ page }) => {
  await page.goto('/settings/ai?tab=text&provider=comfyui');
  await expect(page.locator('h1')).toBeFocused();
  await page.getByText('ComfyUI defaults', { exact: true }).click();
  const form = page.locator('#comfy-text-settings-form');
  const tokens = page.getByLabel('Maximum output tokens', { exact: true });
  const original = await tokens.inputValue();
  const next = original === '4096' ? '8192' : '4096';
  await tokens.fill(next);
  await provider(page, 'OpenRouter').click();
  await expect(tokens).toHaveCount(0);
  await provider(page, 'Defaults & profiles').click();
  await expect(tokens).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Request timeout' })).toBeVisible();
  const timeout = page.getByLabel('Text inactivity timeout in seconds', { exact: true });
  const timeoutBefore = await timeout.inputValue();
  const timeoutDraft = timeoutBefore === '505' ? '506' : '505';
  await timeout.fill(timeoutDraft);
  await provider(page, 'ComfyUI').click();
  await expect(tokens).toHaveValue(next);
  await form.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(tokens).toHaveValue(original);
  await tokens.fill(next);
  await form.getByRole('button', { name: 'Save generation defaults', exact: true }).click();
  await expect(page.getByText('ComfyUI generation defaults saved.', { exact: true })).toBeVisible();
  await provider(page, 'Defaults & profiles').click(); await expect(timeout).toHaveValue(timeoutDraft);
  await page.reload(); await expect(page.locator('h1')).toBeFocused();
  await provider(page, 'Defaults & profiles').click();
  await expect(timeout).toHaveValue(timeoutBefore);
  await provider(page, 'ComfyUI').click(); await page.getByText('ComfyUI defaults', { exact: true }).click(); await expect(tokens).toHaveValue(next);
  await page.setViewportSize({ width: 1173, height: 1272 });
  await page.screenshot({ path: 'artifacts/comfy-text-settings-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/comfy-text-settings-mobile.png', fullPage: true });
  await tokens.fill(original);
  await form.getByRole('button', { name: 'Save generation defaults', exact: true }).click();
  await expect(page.getByText('ComfyUI generation defaults saved.', { exact: true })).toBeVisible();
});

test('provider catalogs preserve filters, pages, aliases and keyboard focus across navigation', async ({ page, request }) => {
  const { id } = await (await request.get('/fixtures/new')).json();
  const { slug } = await (await request.get(`/fixtures/${id}/project-route`)).json();
  const origin = `/projects/${slug}/assets?view=grid#focus`;
  const before = await snapshot(request);
  await page.setViewportSize({ width: 1173, height: 1272 });
  await page.goto(`/settings/ai?tab=text&provider=openrouter&returnUrl=${encodeURIComponent(origin)}`);
  await expect(provider(page, 'OpenRouter')).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('.text-model-row')).toHaveCount(25);
  await expect(page.getByRole('button', { name: 'Set default', exact: true })).toHaveCount(0);
  await provider(page, 'Defaults & profiles').click();
  const defaultBefore = await page.locator('#global-text-default').inputValue();
  await provider(page, 'OpenRouter').click();
  await expect.poll(async () => (await snapshot(request)).checks.OpenRouter).toBe((before.checks.OpenRouter || 0) + 1);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await page.locator('.text-model-expand').first().click();
  await page.getByLabel('Alias', { exact: true }).fill('Unfinished alias');
  await provider(page, 'OpenRouter').focus(); await page.keyboard.press('Home');
  await expect(provider(page, 'ComfyUI')).toBeFocused();
  await expect(page.getByLabel('Alias', { exact: true })).toHaveCount(0);
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'Refresh ComfyUI models', exact: true })).toBeFocused();
  await page.getByLabel('Search text models', { exact: true }).fill('Mock script');
  await section(page, 'Image models').click(); await section(page, 'Text models').click();
  await expect(page.getByLabel('Search text models', { exact: true })).toHaveValue('Mock script');
  // Arrow keys follow the tab order: ComfyUI, OpenAI-compatible, OpenRouter, …
  await provider(page, 'OpenAI-compatible').focus(); await page.keyboard.press('ArrowDown');
  await expect(provider(page, 'OpenRouter')).toBeFocused();
  await expect(page.getByText('Page 2 of 2', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Alias', { exact: true })).toHaveValue('Unfinished alias');
  await expect.poll(async () => (await snapshot(request)).checks.OpenRouter).toBe((before.checks.OpenRouter || 0) + 1);
  await expect(page.locator('.writing-back')).toHaveAttribute('href', origin);
  await provider(page, 'Defaults & profiles').click();
  await expect(page.locator('#global-text-default')).toHaveValue(defaultBefore);
  await provider(page, 'OpenRouter').click();
  await page.getByRole('button', { name: 'Cancel alias', exact: true }).click();
  await page.locator('[role=columnheader][data-column=input] button').click();
  await expect(page.locator('.text-model-expand').first()).toHaveText('Free writing model');
  await page.locator('.text-model-expand').first().click();
  await page.screenshot({ path: 'artifacts/text-settings-desktop.png', fullPage: true });
  await page.reload();
  // The provider selection is page state; a reload opens the first provider.
  await expect(provider(page, 'ComfyUI')).toHaveAttribute('aria-selected', 'true');
  await provider(page, 'OpenRouter').click();
  await expect(page.locator('#model-sort')).toHaveValue('name');
  await expect(page.locator('.writing-back')).toHaveAttribute('href', origin);
});

