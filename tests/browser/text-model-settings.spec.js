test('column headings toggle sort direction by keyboard and mobile has equivalent controls', async ({ page }) => {
  await page.setViewportSize({ width: 1173, height: 1272 });
  await page.goto('/settings/ai?tab=text&provider=openrouter');
  await expect(page.locator('h1')).toBeFocused();
  const heading = key => page.locator(`[role=columnheader][data-column=${key}]`);
  await expect(heading('name')).toHaveAttribute('aria-sort', 'ascending');
  await expect(page.getByRole('columnheader')).toHaveCount(6);
  await heading('added').getByRole('button').focus(); await page.keyboard.press('Enter');
  await expect(heading('added')).toHaveAttribute('aria-sort', 'descending');
  await expect(page.locator('.text-model-expand').first()).toHaveText('Catalog model 30');
  await expect(page.locator('.text-model-row').first().locator('[data-column=added]')).toContainText('2026-01-31');
  await page.keyboard.press('Space');
  await expect(heading('added')).toHaveAttribute('aria-sort', 'ascending');
  await expect(page.locator('.text-model-expand').first()).toHaveText('Catalog model 01');
  await heading('popularity').getByRole('button').click();
  await expect(page.locator('.text-model-row').first().locator('[data-column=popularity]')).toContainText('#1');
  await heading('popularity').getByRole('button').click();
  await expect(heading('popularity')).toHaveAttribute('aria-sort', 'descending');
  await expect(page.locator('.text-model-row').first().locator('[data-column=popularity]')).toContainText('#30');
  await provider(page, 'ComfyUI').click();
  await expect(page.getByRole('columnheader')).toHaveCount(4);
  await provider(page, 'OpenRouter').click();
  await expect(heading('popularity')).toHaveAttribute('aria-sort', 'descending');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('columnheader')).toHaveCount(0);
  await expect(page.getByLabel('Sort', { exact: true })).toHaveValue('popularity');
  await page.getByRole('button', { name: 'Switch to ascending order', exact: true }).click();
  await expect(page.locator('.text-model-expand').first()).toHaveText('Catalog model 01');
  await page.getByLabel('Sort', { exact: true }).selectOption('added');
  await expect(page.locator('.text-model-expand').first()).toHaveText('Catalog model 30');
  await page.setViewportSize({ width: 1173, height: 1272 });
  await expect(heading('added')).toHaveAttribute('aria-sort', 'descending');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
