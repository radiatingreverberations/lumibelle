import { test, expect } from './fixtures.js';
import { closeShotSetup, toolsTab } from './workspace-tools.js';

for (const narrow of [false, true]) test(`editable silent motion reference (${narrow ? 'narrow' : 'desktop'})`, async ({ page, request }) => {
  test.setTimeout(100000);
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/approved`);
  await request.post(`/fixtures/${id}/production-shot`);
  expect((await request.post(`/fixtures/${id}/motion-reference-setup`)).ok()).toBe(true);
  const state = async () => (await request.get(`/fixtures/${id}/shots`)).json();
  await page.setViewportSize({ width: narrow ? 390 : 1173, height: narrow ? 844 : 1000 });
  await page.goto(`/projects/${id}/shots`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  await toolsTab(page, 'Generate');
  await closeShotSetup(page);
  await page.getByRole('button', { name: 'Generate takes', exact: true }).click();
  await expect.poll(async () => (await state()).takes.length, { timeout: 45000 }).toBe(1);
  const original = (await state()).takes[0];
  await page.goto(`/projects/${id}/shots?view=Takes`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const card = page.locator(`[data-take-id='${original.id}']`);
  await card.getByRole('button', { name: 'Use this take', exact: true }).click();
  await expect.poll(async () => (await state()).shots[0].selectedTakeId).toBe(original.id);
  await card.getByRole('button', { name: 'Refine from video…', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Refine from video', exact: true });
  await expect(dialog.getByLabel('Shared output resolution')).toHaveValue('default');
  await expect(dialog.locator('.refine-facts')).toContainText('→ Native · 1 MP');
  await expect(dialog.getByLabel(/^Base prompt for /)).toHaveValue(original.snapshot.prompt.replaceAll('\r\n', '\n'));
  await expect(dialog).toContainText('soundtrack excluded');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await card.getByRole('button', { name: 'Refine from video…', exact: true }).click();
  await dialog.getByLabel('Motion-reference instructions', { exact: true }).fill('Keep the action order and camera. Generate clean new dialogue.');
  await dialog.getByRole('button', { name: 'Manage references', exact: true }).click();
  const references = page.getByRole('dialog', { name: 'Manage references', exact: true });
  if (narrow) await references.getByRole('tab', { name: 'Selected references (1)', exact: true }).click();
  await references.getByRole('button', { name: 'Video 1: Reference settings', exact: true }).click();
  await expect(references.getByLabel('Use audio', { exact: true })).toBeDisabled();
  await expect(references.getByLabel('Use audio', { exact: true })).not.toBeChecked();
  await expect(references.getByLabel('Visuals', { exact: true })).toBeDisabled();
  await references.getByRole('button', { name: 'Apply changes', exact: true }).click();
  await expect(references).not.toBeVisible();
  await expect(dialog.getByLabel('Motion-reference instructions', { exact: true })).toHaveValue('Keep the action order and camera. Generate clean new dialogue.');
  await dialog.getByText('Submitted prompt preview', { exact: true }).click();
  await expect(dialog.locator('.refine-preview')).toContainText('Motion reference <Video 1>: Keep the action order');
  await expect(dialog.getByRole('button', { name: 'Queue refinement', exact: true })).toBeEnabled();
  await page.screenshot({ path: `artifacts/motion-reference-dialog-${narrow ? 'narrow' : 'desktop'}.png` });
  await dialog.getByRole('button', { name: 'Queue refinement', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect.poll(async () => (await state()).takes.length, { timeout: 45000 }).toBe(2);
  const result = (await state()).takes.find(t => t.id !== original.id);
  expect([result.width, result.height]).toEqual([1344, 768]);
  expect(result.seed).not.toBe(original.seed);
  expect(result.snapshot.motionReference.takeId).toBe(original.id);
  expect(result.snapshot.shot.duration).toBe(original.snapshot.shot.duration);
  expect(result.snapshot.shot.videos.at(-1).useSoundtrack).toBe(false);
  expect(result.snapshot.prompt.split('Motion reference <Video 1>:')).toHaveLength(2);
  expect(result.snapshot.motionReference.basePrompt).toBe(original.snapshot.prompt);
  expect(result.generationRecipe.version).toBe('h3-generation-recipe-v1');
  expect((await state()).shots[0].selectedTakeId).toBe(original.id);
  expect((await state()).takes.find(t => t.id === original.id).snapshot.prompt).toBe(original.snapshot.prompt);
  await page.reload();
  await expect(page.locator(`[data-take-id='${result.id}']`)).toBeVisible();
  await expect(page.locator(`[data-take-id='${result.id}']`)).not.toContainText('Script changed');
  await page.locator(`[data-take-id='${result.id}']`).getByRole('button', { name: 'Refine from video…', exact: true }).click();
  await expect(dialog.getByLabel(/^Base prompt for /)).toHaveValue(original.snapshot.prompt.replaceAll('\r\n', '\n'));
  await expect(dialog).toContainText('1 videos');
  await dialog.getByText('Submitted prompt preview', { exact: true }).click();
  expect((await dialog.locator('.refine-preview').innerText()).split('Motion reference <Video 1>:')).toHaveLength(2);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  expect((await state()).takes).toHaveLength(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `artifacts/motion-reference-${narrow ? 'narrow' : 'desktop'}.png` });
});
