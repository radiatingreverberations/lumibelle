import { test, expect } from './fixtures.js';
import { openPlanning, planningComposer, submitPlanning } from './text-assistance-tools.js';

for (const width of [1440, 430]) test(`Scene inspection views survive review and drafting at ${width}px`, async ({ page, request }) => {
  test.setTimeout(150000);
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/images`);
  await request.post(`/fixtures/${id}/approved`);
  await request.post(`/fixtures/${id}/production-shot`);
  const take = await (await request.post(`/fixtures/${id}/reference-video-take`)).json();
  expect((await request.post(`/fixtures/${id}/reference-reels?takeId=${take.id}`)).ok()).toBe(true);
  const library = await (await request.post(`/fixtures/${id}/environment-library`)).json();
  const owner = library.assets[0];
  await page.setViewportSize({ width, height: 1000 });
  await page.goto(`/projects/${id}/shots`);
  await expect(page.locator('.shots-heading')).toHaveAttribute('data-interactive', 'true');
  await openPlanning(page);
  const composer = planningComposer(page);
  await composer.locator('.model-chip').click();
  await page.getByRole('combobox', { name: 'Text model', exact: true }).selectOption({ label: 'OpenRouter · Alternate mock model' });
  await page.getByRole('button', { name: 'Set as project default', exact: true }).click();
  await composer.getByLabel('Directing instructions (optional)').fill('Keep the deliberate pause.');
  await composer.getByRole('button', { name: 'Choose environment views', exact: true }).first().click();
  const picker = page.getByRole('dialog', { name: 'Environment for drafting', exact: true });
  await expect(composer).toBeHidden();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await picker.getByRole('combobox', { name: 'Environment', exact: true }).selectOption(owner.id);
  await picker.getByLabel('Staging constraints').fill('Riley is shorter than the podium.');
  await picker.getByRole('button', { name: 'Choose views with AI', exact: true }).click();
  await expect(picker).toContainText('All available sources inspected.', { timeout: 30000 });
  await expect(picker.locator('.environment-view-card input:checked')).not.toHaveCount(0);
  await picker.getByRole('button', { name: /Include saved views/ }).first().click();
  await page.screenshot({ path: `test-results/drafting-environment-${width}.png`, fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await picker.getByRole('button', { name: 'Save scene setup', exact: true }).click();
  await expect(composer).toBeVisible();
  await expect(composer.getByLabel('Directing instructions (optional)')).toHaveValue('Keep the deliberate pause.');
  await expect(composer).toContainText('Riley is shorter than the podium.');
  const state = async () => (await (await request.get(`/fixtures/${id}/shots`)).json());
  const before = await state();
  const setup = before.sceneSetups.find(s => s.environment);
  expect(setup.environment.assetId).toBe(owner.id);
  expect(setup.environment.views.length).toBeGreaterThan(1);
  await submitPlanning(page);
  const review = page.locator('.shot-planning-dialog');
  await expect(review.getByLabel('Set assessment')).toHaveValue(/visible standing side/);
  await review.getByLabel('Set assessment').fill('Keep the obstruction; cover the reaction from the side.');
  const assessment = review.locator('.draft-environment-review');
  await assessment.getByText('Evidence and assumptions', { exact: true }).click();
  const claim = assessment.locator('.environment-claim').first();
  await claim.locator('summary').click();
  // A Supported claim cannot silently lose all its inspected evidence.
  await claim.getByRole('checkbox').filter({ visible: true }).first().uncheck();
  await expect(assessment.getByRole('alert')).toContainText('supported claim needs');
  await claim.getByLabel('Claim support').selectOption('Inferred');
  await claim.getByLabel('Claim text').fill('The platform identity is uncertain; use the standing side.');
  for (const evidence of await claim.getByRole('checkbox').all()) await evidence.uncheck();
  await claim.getByLabel('Claim support').selectOption('Supported');
  await expect(assessment.getByRole('alert')).toContainText('supported claim needs');
  await expect(claim.getByLabel('Claim support')).toHaveValue('Inferred');
  await claim.getByRole('checkbox').last().check();
  await assessment.locator('.environment-claim').last().locator('summary').click();
  await assessment.locator('.environment-claim').last().getByRole('button', { name: 'Remove claim', exact: true }).click();
  await review.getByRole('button', { name: 'Close', exact: true }).click();
  const jobs = (await (await request.get('/fixtures/ai-jobs')).json()).filter(j => j.target.projectId === id);
  const draft = jobs.find(j => j.kind === 'ShotPlanning');
  await page.goto(`/projects/${id}/shots?jobId=${draft.id}`);
  await expect(review.getByLabel('Set assessment')).toHaveValue('Keep the obstruction; cover the reaction from the side.');
  await review.getByText('Evidence and assumptions', { exact: true }).click();
  await review.locator('.environment-claim summary').click();
  await expect(review.getByLabel('Claim text')).toHaveValue('The platform identity is uncertain; use the standing side.');
  await expect(review.getByLabel('Claim support')).toHaveValue('Inferred');
  await expect(review.locator('.environment-claim input:checked')).toHaveCount(1);
  const response = review.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Response details/ }) });
  await response.locator('summary').click();
  await expect(response.locator('pre')).toContainText('The platform is established.');
  await response.locator('summary').click();
  await page.screenshot({ path: `test-results/drafting-claim-review-${width}.png`, fullPage: true, animations: 'disabled' });
  await review.getByRole('button', { name: 'Add reviewed shots', exact: true }).click();
  await expect.poll(async () => (await state()).shots.length).toBe(before.shots.length + 1);
  const added = (await state()).shots.find(s => !before.shots.some(b => b.id === s.id));
  expect(added.environmentAssetId).toBe(owner.id);
  expect(added.images).toHaveLength(0); expect(added.videos).toHaveLength(0);
  expect(added.draftingEnvironment.assessment.summary).toContain('Keep the obstruction');
  expect(added.draftingEnvironment.assessment.claims).toHaveLength(1);
  expect(added.draftingEnvironment.assessment.claims[0].claim).toContain('platform identity is uncertain');
  expect(added.draftingEnvironment.assessment.claims[0].status).toBe('Inferred');
  expect(added.draftingEnvironment.snapshot.views.length).toBe(setup.environment.views.length);
  expect(jobs.filter(j => j.kind === 'Video')).toHaveLength(0);
});
