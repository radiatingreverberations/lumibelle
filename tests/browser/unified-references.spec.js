test('failed combined save retries once and preserves immediate manual prompt edits', async ({ page, request }) => {
  const { id, library, editor } = await fixture(page, request);
  await openShotSetup(page);
  const prompt = page.getByRole('textbox', { name: 'H3 prompt', exact: true }); await prompt.fill('Manual 日本語 prompt');
  await open(page); await editor.locator('[data-reference]').first().click(); await editor.locator(`[data-reel-id="${library.reels[0].id}"] .add-reel`).click();
  await editor.getByLabel('Voice for Juniper', { exact: true }).selectOption('none');
  await request.post(`/fixtures/${id}/reference-save-failure?fail=true`);
  await editor.getByRole('button', { name: 'Apply changes', exact: true }).click(); await expect(editor.getByRole('alert')).toContainText('Fixture storage unavailable');
  expect((await state(request, id)).inputs.images).toHaveLength(0);
  await request.post(`/fixtures/${id}/reference-save-failure?fail=false`);
  await editor.getByRole('button', { name: 'Apply changes', exact: true }).click(); await expect(editor).not.toBeVisible();
  let saved = await state(request, id); expect(saved.inputs.images).toHaveLength(1); expect(saved.inputs.videos).toHaveLength(1); expect(saved.prompt).toBe('Manual 日本語 prompt');
  await page.locator('.shots-heading').getByRole('button', { name: 'Undo', exact: true }).click();
  await expect.poll(async () => (await state(request, id)).inputs.images.length).toBe(0);
  saved = await state(request, id); expect(saved.inputs.videos).toHaveLength(0); expect(saved.prompt).toBe('Manual 日本語 prompt');
});
