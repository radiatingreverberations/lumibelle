  await editor.getByRole('button',{name:'Redo',exact:true}).click();
  await expect(inputCrop).toContainText('Cropped · 32 × 40');
  await inputCrop.getByRole('button',{name:'Adjust input crop',exact:true}).click();
  await expect(editor.getByRole('combobox',{name:'Paint',exact:true})).toHaveValue('context');
