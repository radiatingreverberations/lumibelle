  const canvas=editor.locator('canvas');const bounds=await canvas.boundingBox();
  await page.mouse.move(bounds.x+bounds.width*.45,bounds.y+bounds.height*.5);
  await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.55,bounds.y+bounds.height*.5,{steps:5});await page.mouse.up();
  await expect(editor).toContainText('2 edit strokes');
  const inputCrop=editor.getByRole('group',{name:'Input crop',exact:true});
  await expect(inputCrop).toContainText('Full image · 64 × 80');
  await inputCrop.getByRole('button',{name:'Crop input to selection',exact:true}).click();
  await expect(inputCrop).toContainText('Cropped · 32 × 40');
