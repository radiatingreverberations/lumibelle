import { test, expect } from './fixtures.js';

for (const width of [1280, 390]) test(`bulk batches select one asset type and capture batch direction at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 960 });
  const { id } = await (await request.get('/fixtures/new')).json();
  await request.post(`/fixtures/${id}/bulk-types`);
  await request.post('/fixtures/bulk-assets/vision');
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const toggle = page.locator('[data-toggle-pane=left]');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await page.locator('.bulk-assets-launch').click();
  const dialog = page.locator('.asset-batch-dialog');
  const filters = dialog.getByRole('group', { name: 'Asset type', exact: true });
  await expect(dialog.locator('.bulk-plan-card')).toHaveCount(4);
  await expect(dialog.locator('.bulk-instructions')).not.toHaveAttribute('open');
  await filters.getByRole('button', { name: /^Characters/ }).click();
  await expect(filters.getByRole('button', { name: /^Characters/ })).toHaveAttribute('aria-pressed', 'true');
  await expect(filters.getByRole('button', { name: /^All/ })).toHaveAttribute('aria-pressed', 'false');
  await expect(dialog.locator('.bulk-plan-card')).toHaveCount(2);
  await expect(dialog.locator('.bulk-plan-card').filter({ hasText: 'Raincoat' }).getByRole('checkbox')).toBeDisabled();
  await dialog.getByRole('button', { name: 'Select all ready items', exact: true }).click();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('1 items');
  await expect(dialog.getByLabel('Aspect', { exact: true })).toBeVisible();
  await dialog.getByLabel('Aspect', { exact: true }).selectOption('9:16');
  await filters.scrollIntoViewIfNeeded();
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.screenshot({ path: testInfo.outputPath(`character-batch-selection-${width}.png`) });
  await dialog.locator('.bulk-instructions summary').click();
  const characterDirection = 'Full-body view. Keep the entire figure visible, including the feet.';
  await dialog.getByLabel('Instructions for this batch').fill(characterDirection);
  await dialog.getByRole('checkbox', { name: 'Evaluate candidates with a vision model' }).check();
  await dialog.getByRole('button', { name: 'Review generation plan', exact: true }).click();
  await expect(dialog.locator('.bulk-plan-card')).toHaveCount(1);
  await expect(dialog.locator('.bulk-plan-summary')).toContainText('Characters · 1 items · 9:16');
  await expect(dialog.locator('.bulk-item-instructions')).toContainText(characterDirection);
  await expect(dialog.getByRole('button', { name: 'Start batch', exact: true })).toBeEnabled();
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.screenshot({ path: testInfo.outputPath(`character-batch-plan-${width}.png`) });
  await dialog.getByRole('button', { name: 'Start batch', exact: true }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 40000 });
  await dialog.getByRole('button', { name: 'New batch', exact: true }).click();
  await filters.getByRole('button', { name: /^Environments/ }).click();
  await expect(dialog.locator('.bulk-plan-card')).toHaveCount(1);
  await expect(dialog.locator('.bulk-plan-card')).toContainText('Workshop');
  await dialog.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Review generation plan' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Select all ready items', exact: true }).click();
  await dialog.getByLabel('Aspect', { exact: true }).selectOption('16:9');
  await dialog.locator('.bulk-instructions summary').click();
  await expect(dialog.getByLabel('Instructions for this batch')).toHaveValue('');
  const environmentDirection = 'Wide establishing view. Include the floor and ceiling.';
  await dialog.getByLabel('Instructions for this batch').fill(environmentDirection);
  await dialog.getByRole('button', { name: 'Review generation plan' }).click();
  await expect(dialog.locator('.bulk-plan-summary')).toContainText('Environments · 1 items · 16:9');
  await expect(dialog.locator('.bulk-item-instructions')).toContainText(environmentDirection);
  await dialog.getByRole('button', { name: 'Start batch', exact: true }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 40000 });
  const runs = await (await request.get(`/fixtures/${id}/asset-batches`)).json();
  expect(runs).toHaveLength(2);
  expect(runs[0].aspectRatio).toBe('9:16');
  expect(runs[0].items.map(i => i.assetName)).toEqual(['Juniper']);
  expect(runs[0].items[0].additionalInstructions).toBe(characterDirection);
  expect(runs[1].aspectRatio).toBe('16:9');
  expect(runs[1].items.map(i => i.assetName)).toEqual(['Workshop']);
  const captured = await (await request.get(`/fixtures/${id}/visual-style`)).json();
  expect(captured.generation.map(g => g.aspectRatio)).toEqual(['9:16', '16:9']);
  expect(captured.generation[0].prompt).toContain(characterDirection);
  expect(captured.generation[1].prompt).toContain(environmentDirection);
  expect(captured.reviews).toHaveLength(2);
  expect(captured.reviews[0].prompt).toContain(characterDirection);
  expect(captured.reviews[1].prompt).toContain(environmentDirection);
});
