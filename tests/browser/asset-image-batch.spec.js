import { test, expect } from './fixtures.js';

for (const width of [1280, 390]) test(`bulk images preserve a reviewed plan, resume and await human approval at ${width}px`, async ({ page, request }, testInfo) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width, height: 960 });
  const { id } = await (await request.get('/fixtures/new')).json();
  const library = await (await request.post(`/fixtures/${id}/images`)).json();
  await request.post('/fixtures/bulk-assets/vision');
  await page.goto(`/projects/${id}/assets`);
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  const launch = page.locator('.bulk-assets-launch');
  const toggle = page.locator('[data-toggle-pane=left]');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await expect(launch.locator('.ai-assist-icon')).toBeVisible();
  const extractSize = await page.locator('.asset-library-extraction .request-action-button').boundingBox();
  const bulkSize = await launch.boundingBox();
  expect(Math.abs(extractSize.width - bulkSize.width)).toBeLessThanOrEqual(1);
  expect(Math.abs(extractSize.height - bulkSize.height)).toBeLessThanOrEqual(1);
  await launch.click();
  const dialog = page.locator('.asset-batch-dialog');
  await expect(dialog).toBeVisible();
  await expect(dialog.locator('.bulk-steps .active')).toContainText('Choose assets');
  await dialog.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('0 items');
  await dialog.locator('.bulk-plan-card').first().getByRole('checkbox').check();
  await expect(dialog.locator('.bulk-select-actions')).toContainText('1 items');
  await dialog.getByRole('checkbox', { name: 'Evaluate candidates with a vision model' }).check();
  await dialog.getByRole('button', { name: 'Review generation plan' }).click();
  await dialog.getByLabel('Generation prompt').fill('SLOW A small green robot on a plain background. Preserve the readable silhouette.');
  await expect(dialog.getByRole('button', { name: 'Start batch', exact: true })).toBeEnabled();
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.screenshot({ path: testInfo.outputPath(`bulk-plan-${width}.png`) });
  await dialog.getByRole('button', { name: 'Start batch', exact: true }).click();
  await expect(dialog.locator('.bulk-steps .active')).toContainText('Generate & review');
  await dialog.getByRole('button', { name: 'Pause after current request' }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch paused');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload();
  await expect(page.locator('.studio-workspace')).toHaveAttribute('data-ready', 'true');
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click();
  await launch.click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch paused');
  await dialog.getByRole('button', { name: 'Resume batch' }).click();
  await expect(dialog.locator('.bulk-run-status')).toContainText('Batch complete', { timeout: 40000 });
  await expect(dialog.locator('.bulk-candidate')).toHaveCount(2);
  await expect(dialog.locator('.bulk-candidate').first()).toContainText('Clear framing');
  await dialog.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(launch).toContainText('Review bulk assets · 1');
  await expect(page.locator('.asset-library-bulk .request-ready')).toBeVisible();
  await expect(launch.locator('.ai-assist-icon')).toBeVisible();
  await page.locator('.asset-library-bulk').screenshot({ path: testInfo.outputPath(`bulk-review-button-${width}.png`) });
  await launch.click();
  await dialog.getByRole('button', { name: 'Compare & details', exact: true }).first().click();
  const viewer = page.locator('.image-review-dialog');
  await expect(viewer).toBeVisible();
  await viewer.getByRole('button', { name: 'Compare with Candidate 2', exact: true }).click();
  await expect(viewer.locator('.review-wipe')).toBeVisible();
  await expect(viewer.getByRole('button', { name: 'Edit image', exact: true })).toHaveCount(0);
  await viewer.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(dialog).toBeVisible();
  const before = await (await request.get(`/fixtures/${id}`)).json();
  expect(before.assets.assets[0].images.filter(image => image.isReference)).toHaveLength(0);
  await dialog.getByRole('button', { name: 'Use as reference', exact: true }).first().click();
  await expect(dialog.locator('.bulk-approved')).toContainText('Reference approved');
  await expect(launch).toContainText('Review bulk assets · 1');
  await dialog.getByRole('button', { name: 'Keep as take', exact: true }).click();
  await expect(dialog.locator('.bulk-review-complete')).toBeVisible();
  await expect(launch).toHaveText('Bulk assets');
  await expect(page.locator('.asset-library-bulk .request-ready')).toHaveCount(0);
  await dialog.screenshot({ path: testInfo.outputPath(`bulk-results-${width}.png`) });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.getByRole('button', { name: 'New batch', exact: true }).click();
  await expect(dialog.locator('.bulk-plan-list')).toBeVisible();
  await page.waitForTimeout(2300); // A periodic refresh must not reopen the previous run.
  await expect(dialog.locator('.bulk-plan-list')).toBeVisible();
  await expect(dialog.getByLabel('Saved batches')).toHaveCount(1);
  expect(library.assets[0].id).toBeTruthy();
});
